// Generates every derived token artifact from spec/tokens.json:
//   packages/core/css/tokens.css      CSS custom properties (:root, .dark, [data-shape="rounded"])
//   packages/core/css/tailwind.css    the Tailwind v4 preset: @theme, token utilities, custom variants
//   components/lib/tv.ts              tv() configured with the token class names: the one-time setup
//                                     every recipe imports (installed once, like shadcn's lib/utils.ts)
//   packages/core/src/tokens.ts       typed token table + var() helpers
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(fs.readFileSync(path.join(ROOT, "spec/tokens.json"), "utf8"));
const P = spec.prefix;
const MODES = spec.modes;
const GROUPS = Object.keys(spec).filter((k) => !k.startsWith("$") && typeof spec[k] === "object" && !Array.isArray(spec[k]));

const HEADER = (c) => `${c} GENERATED by scripts/build-tokens.mjs from spec/tokens.json — do not edit.\n`;

/* ── helpers ─────────────────────────────────────────────── */
const tokensOf = (group) => Object.entries(spec[group]).filter(([k]) => !k.startsWith("$"));
const isModal = (v) => v && typeof v === "object" && !Array.isArray(v) && MODES.every((m) => m in v);
const forMode = (v, mode) => (isModal(v) ? v[mode] : v);
const cssVarName = (group, name) => (group === "color" ? `--${P}-${name}` : `--${P}-${group}-${name}`);

/* alias "{color.line}" → css var */
const ALIAS = /^\{([a-z]+)\.([a-z0-9-]+)\}$/;
function cssAlias(str) {
  const m = ALIAS.exec(str);
  return m ? `var(${cssVarName(m[1], m[2])})` : str;
}

function toCss(type, value) {
  switch (type) {
    case "shadow":
      return value
        .map((l) => `${l.inset ? "inset " : ""}${l.x} ${l.y} ${l.blur} ${l.spread} ${cssAlias(l.color)}`)
        .join(", ");
    case "fontFamily":
      return value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
    case "cubicBezier":
      return `cubic-bezier(${value.join(", ")})`;
    default:
      return typeof value === "string" ? cssAlias(value) : String(value);
  }
}

/* ── CSS ─────────────────────────────────────────────────── */
function buildCss() {
  const root = [];
  const dark = [];
  const rounded = [];
  const reduced = [];
  for (const g of GROUPS) {
    const type = spec[g].$type;
    root.push(`  /* ${g} */`);
    for (const [name, tok] of tokensOf(g)) {
      const v = tok.$value;
      root.push(`  ${cssVarName(g, name)}: ${toCss(type, forMode(v, "light"))};`);
      if (isModal(v)) dark.push(`  ${cssVarName(g, name)}: ${toCss(type, v.dark)};`);
      if (tok.$rounded !== undefined) rounded.push(`  ${cssVarName(g, name)}: ${toCss(type, tok.$rounded)};`);
      if (tok.$reducedMotion !== undefined) reduced.push(`    ${cssVarName(g, name)}: ${toCss(type, tok.$reducedMotion)};`);
    }
  }
  return (
    HEADER("/*").replace("\n", " */\n") +
    `:root {\n  color-scheme: light;\n${root.join("\n")}\n}\n\n` +
    `.dark,\n[data-theme="dark"] {\n  color-scheme: dark;\n${dark.join("\n")}\n}\n\n` +
    `/* The shape of a part of a page. Buttons, toggles and segmented controls that name no shape of\n` +
    ` * their own are pills; under an element that carries data-shape="rounded" they take a field's\n` +
    ` * corners. (A project sets its whole app's shape in fndn.json, which the tool writes into config.css.) */\n` +
    `[data-shape="rounded"] {\n${rounded.join("\n")}\n}\n\n` +
    `/* Reduced motion keeps fades and colour, drops travel: these tokens carry the difference. */\n` +
    `@media (prefers-reduced-motion: reduce) {\n  :root {\n${reduced.join("\n")}\n  }\n}\n`
  );
}

/* what each motion-<what>-* utility transitions */
const MOTION_SLOTS = {
  colors: ["color", "background-color", "border-color", "text-decoration-color", "fill", "stroke"],
  opacity: ["opacity"],
  shadow: ["box-shadow"],
  transform: ["transform", "translate", "scale", "rotate"],
  filter: ["filter", "backdrop-filter"],
  size: ["width", "height", "grid-template-rows", "grid-template-columns"],
  radius: ["border-radius"],
};

function buildTailwind() {
  const theme = [];
  const utilities = [];
  /* Tailwind's own type scale pairs each size with a line-height; ours sets the size only */
  const TW_TEXT = new Set(["xs", "sm", "base", "lg", "xl", "2xl", "3xl", "4xl", "5xl", "6xl", "7xl", "8xl", "9xl"]);
  for (const g of GROUPS) {
    for (const [name] of tokensOf(g)) {
      const v = `var(${cssVarName(g, name)})`;
      if (g === "color") theme.push(`  --color-${name}: ${v};`);
      else if (g === "shadow") theme.push(`  --shadow-${name}: ${v};`);
      else if (g === "radius") theme.push(`  --radius-${name}: ${v};`);
      else if (g === "font") theme.push(`  --font-${name}: ${v};`);
      else if (g === "text") { theme.push(`  --text-${name}: ${v};`); if (TW_TEXT.has(name)) theme.push(`  --text-${name}--line-height: initial;`); }
      else if (g === "easing") theme.push(`  --ease-${name}: ${v};`);
      else if (g === "duration") {
        utilities.push(`@utility duration-${name} { --tw-duration: ${v}; transition-duration: ${v}; }`);
        utilities.push(`@utility delay-${name} { transition-delay: ${v}; }`);
      } else if (g === "z") utilities.push(`@utility z-${name} { z-index: ${v}; }`);
      /* the system's scales (press, popup) set `transform`, not `scale`: the tests
       * and the transitions (motion-transform-*) read that property */
      else if (g === "motion" && /scale/.test(name)) {
        const short = name.replace(/-scale/, "");
        utilities.push(`@utility scale-${short} { transform: scale(${v}); }`);
        /* squeeze-*: the same amount on the separate \`scale\` property, for a part whose position is
         * already a transform or a translate (a thumb): the two then keep their own transitions */
        utilities.push(`@utility squeeze-${short} { scale: ${v}; }`);
        /* scale-y-popup: the popup scale along the block axis only, for a popup as wide as its
         * trigger (a select's list). A scale takes a share of the width, so a wide list would
         * travel far sideways; this one's sides stay on the trigger's sides */
        if (name === "popup-scale") utilities.push(`@utility scale-y-${short} { transform: scaleY(${v}); }`);
      }
    }
  }
  /* motion: named timings (spec.$transitions) and one composable utility per kind of property.
   * motion-colors-fast motion-transform-press gives each kind its own timing on one element, which
   * Tailwind's duration-* cannot (one duration per element). Each utility fills its own slot and
   * rewrites the whole transition list from the slots; an empty slot is a no-op entry. */
  const timings = Object.entries(spec.$transitions ?? {}).filter(([k]) => !k.startsWith("$"));
  for (const [name, [duration, easing]] of timings) {
    theme.push(`  --motion-${name}: var(${cssVarName("duration", duration)}) ${spec.easing?.[easing] ? `var(${cssVarName("easing", easing)})` : easing};`);
  }
  const SLOTS = MOTION_SLOTS;
  const composed = [...Object.keys(SLOTS), "also"].map((slot) => `var(--${P}-m-${slot}, _ 0s)`).join(", ");
  const motion = [];
  for (const slot of [...Object.keys(SLOTS), "also"]) motion.push(`@property --${P}-m-${slot} { syntax: "*"; inherits: false; }`);
  for (const [slot, props] of Object.entries(SLOTS)) {
    motion.push(`@utility motion-${slot}-* { --${P}-m-${slot}: ${props.map((p) => `${p} --value(--motion-*)`).join(", ")}; transition: ${composed}; }`);
  }
  /* anything else, written out: motion-also-[visibility_0s_linear_var(--fndn-duration-fast)] */
  motion.push(`@utility motion-also-* { --${P}-m-also: --value([*]); transition: ${composed}; }`);
  /* the shared keyframes (base.css) as animate-* utilities, with the timing the components use */
  const D = (n) => `var(${cssVarName("duration", n)})`;
  const E = (n) => `var(${cssVarName("easing", n)})`;
  theme.push(`  --animate-fade-up: ${P}-fade-up ${D("enter")} ${E("out-strong")} both;`);
  theme.push(`  --animate-fade-in: ${P}-fade-in ${D("base")} ease both;`);
  theme.push(`  --animate-pop-in: ${P}-pop-in ${D("popup")} ${E("out-strong")} both;`);
  return (
    HEADER("/*").replace("\n", " */\n") +
    `/* The system's Tailwind preset. In a Tailwind v4 stylesheet, after \`@import "tailwindcss"\` and
 * tokens.css: bg-surface, text-ink-2, shadow-card, rounded-control, text-sm (size only),
 * ease-out-strong, duration-fast, z-popup, scale-press, animate-fade-up, the motion-* utilities
 * (motion-colors-fast, motion-transform-press) and the variants below. */\n` +
    `@theme inline {\n${theme.join("\n")}\n}\n\n` +
    `${utilities.join("\n")}\n\n` +
    `/* motion-<what>-<timing>: what = ${Object.keys(MOTION_SLOTS).join(" | ")}; timing = ${Object.keys(spec.$transitions ?? {}).filter((k) => !k.startsWith("$")).join(" | ")} */\n` +
    `${motion.join("\n")}\n\n` +
    `/* Tailwind's preflight hides [hidden] with !important in the base layer, and among important rules\n` +
    ` * the EARLIER layer wins. A collapsible region that keeps its layout while closed (keepLayout: so the\n` +
    ` * entrances inside it do not replay on reopen) must stay displayed, so its rule lives in the theme\n` +
    ` * layer, the only one before base. */\n` +
    `@layer theme {\n  [data-keep-layout] > [hidden]:where(.${P}-collapsible__content, [data-slot="collapsible-content"]) { display: grid !important; }\n}\n\n` +
    `/* keyboard-initiated changes are instant: kbd:duration-0 (html[data-${P}-input], set by trackModality) */\n` +
    `@custom-variant kbd (&:where(:root[data-${P}-input="keyboard"] *));\n` +
    `/* kbd-instant: the element skips its transitions (durations and delays) while the last input was the\n` +
    ` * keyboard, whatever its motion utilities say: popups, sliding thumbs, indicators, carets */\n` +
    `@utility kbd-instant {\n  &:where(:root[data-${P}-input="keyboard"] *) {\n    transition-duration: 0ms !important;\n    transition-delay: 0ms !important;\n  }\n}\n` +
    `/* hover only where there is a real pointer; group-hover and peer-hover follow */\n` +
    `@custom-variant hover {\n  @media (hover: hover) and (pointer: fine) {\n    &:hover {\n      @slot;\n    }\n  }\n}\n`
  );
}

/* ── recipes/tv.ts: tv() that knows the token classes ────── */
function buildTv() {
  const names = (g) => tokensOf(g).map(([n]) => n);
  const groups = {
    "font-size": names("text").map((n) => `text-${n}`),
    shadow: names("shadow").map((n) => `shadow-${n}`),
    rounded: names("radius").map((n) => `rounded-${n}`),
    ease: names("easing").map((n) => `ease-${n}`),
    duration: names("duration").map((n) => `duration-${n}`),
    delay: names("duration").map((n) => `delay-${n}`),
    "z-index": names("z").map((n) => `z-${n}`),
    scale: [...names("motion").filter((n) => /scale/.test(n)).flatMap((n) => [`scale-${n.replace(/-scale/, "")}`, `squeeze-${n.replace(/-scale/, "")}`]), "scale-y-popup"],
    animate: ["animate-fade-up", "animate-fade-in", "animate-pop-in"],
  };
  /* one group per motion slot: motion-colors-base replaces motion-colors-fast, not motion-opacity-fast */
  const kinds = Object.keys(spec.$transitions ?? {}).filter((k) => !k.startsWith("$"));
  for (const slot of Object.keys(MOTION_SLOTS)) groups[`motion-${slot}`] = kinds.map((k) => `motion-${slot}-${k}`);
  return (
    HEADER("//") +
    `import { createTV } from "tailwind-variants/config";\n\n` +
    `/** \`tv\` for the recipes. It is told the system's token classes, so a variant's \`text-xs\`,\n` +
    ` * \`shadow-none\` or \`rounded-control\` replaces the base's value and nothing else. The type scale\n` +
    ` * sets the size only, so a font size never removes a line-height (Tailwind's own scale does). */\n` +
    `export const tv = createTV({\n  twMergeConfig: {\n    extend: {\n      classGroups: {\n` +
    Object.entries(groups).map(([k, v]) => `        ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n") +
    `\n      },\n    },\n    override: { conflictingClassGroups: { "font-size": [] } },\n  },\n});\n\n` +
    `export type { VariantProps } from "tailwind-variants";\n`
  );
}

/* ── TypeScript ──────────────────────────────────────────── */
function buildTs() {
  const out = [HEADER("//")];
  out.push(`export const prefix = ${JSON.stringify(P)} as const;`);
  out.push(`export const modes = ${JSON.stringify(MODES)} as const;`);
  out.push(`export type Mode = (typeof modes)[number];\n`);
  out.push(`/** Raw token values straight from the spec (CSS strings, per mode where themed). */`);
  out.push(`export const tokens = {`);
  for (const g of GROUPS) {
    const type = spec[g].$type;
    out.push(`  ${JSON.stringify(g)}: {`);
    for (const [name, tok] of tokensOf(g)) {
      const v = tok.$value;
      const val = isModal(v)
        ? `{ light: ${JSON.stringify(toCss(type, v.light))}, dark: ${JSON.stringify(toCss(type, v.dark))} }`
        : JSON.stringify(toCss(type, v));
      out.push(`    ${JSON.stringify(name)}: ${val},`);
    }
    out.push(`  },`);
  }
  out.push(`} as const;\n`);
  out.push(`/** Values that change under prefers-reduced-motion: reduce (CSS strings). */`);
  out.push(`export const reducedMotion = {`);
  for (const g of GROUPS) {
    const type = spec[g].$type;
    const entries = tokensOf(g).filter(([, tok]) => tok.$reducedMotion !== undefined);
    if (!entries.length) continue;
    out.push(`  ${JSON.stringify(g)}: {`);
    for (const [name, tok] of entries) out.push(`    ${JSON.stringify(name)}: ${JSON.stringify(toCss(type, tok.$reducedMotion))},`);
    out.push(`  },`);
  }
  out.push(`} as const;\n`);
  out.push(`/** CSS custom property names, e.g. vars.color.ink === "--${P}-ink". */`);
  out.push(`export const vars = {`);
  for (const g of GROUPS) {
    out.push(`  ${JSON.stringify(g)}: {`);
    for (const [name] of tokensOf(g)) out.push(`    ${JSON.stringify(name)}: ${JSON.stringify(cssVarName(g, name))},`);
    out.push(`  },`);
  }
  out.push(`} as const;\n`);
  out.push(`export type TokenGroup = keyof typeof vars;`);
  out.push(`export type TokenName<G extends TokenGroup> = keyof (typeof vars)[G];`);
  out.push(`/** \`v("color", "ink")\` → \`var(--${P}-ink)\` */`);
  out.push(`export function v<G extends TokenGroup>(group: G, name: TokenName<G>): string {`);
  out.push(`  return \`var(\${vars[group][name] as string})\`;`);
  out.push(`}`);
  return out.join("\n") + "\n";
}

/* ── write ───────────────────────────────────────────────── */
const write = (rel, content) => {
  const p = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
  console.log("wrote", rel);
};
write("packages/core/css/tokens.css", buildCss());
write("packages/core/css/tailwind.css", buildTailwind());
write("components/lib/tv.ts", buildTv());
write("packages/core/src/tokens.ts", buildTs());
