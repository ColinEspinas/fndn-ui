// spec/icons.json → packages/core/css/icons.css (mask-image icons) and packages/core/src/icons.ts
import fs from "node:fs";
import path from "node:path";
import { ROOT, readJson } from "./lib.mjs";

const spec = readJson("spec/icons.json");
const ASSETS = path.join(ROOT, "node_modules/@phosphor-icons/core/assets");
const HEADER = "GENERATED by scripts/build-icons.mjs from spec/icons.json (Phosphor Icons, MIT) — do not edit.";

const entries = Object.entries(spec.icons).map(([name, def]) => {
  const weight = def.weight ?? spec.defaultWeight;
  const file = path.join(ASSETS, weight, `${def.phosphor}${weight === "regular" ? "" : `-${weight}`}.svg`);
  if (!fs.existsSync(file)) throw new Error(`icon "${name}": ${file} not found`);
  const svg = fs.readFileSync(file, "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
  return { name, weight, phosphor: def.phosphor, inner };
});

const ts = [
  `// ${HEADER}`,
  `export const iconNames = ${JSON.stringify(entries.map((e) => e.name))} as const;`,
  `export type IconName = (typeof iconNames)[number];`,
  `export type IconWeight = "thin" | "light" | "regular" | "bold" | "fill" | "duotone";`,
  `/** The Phosphor icon and weight behind each vocabulary name. */`,
  `export const icons: Record<IconName, { phosphor: string; weight: IconWeight }> = {`,
  ...entries.map((e) => `  ${JSON.stringify(e.name)}: { phosphor: ${JSON.stringify(e.phosphor)}, weight: ${JSON.stringify(e.weight)} },`),
  `};`,
  `/** Inner SVG markup of each icon (viewBox 0 0 256 256, fill currentColor). */`,
  `export const iconPaths: Record<IconName, string> = {`,
  ...entries.map((e) => `  ${JSON.stringify(e.name)}: ${JSON.stringify(e.inner)},`),
  `};`,
  `/** Inline <svg> markup for an icon, for places that cannot use the CSS mask (email, canvas, SSR without the stylesheet). */`,
  `export function iconSvg(name: IconName, attrs = 'width="1em" height="1em"'): string {`,
  `  return \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true" \${attrs}>\${iconPaths[name]}</svg>\`;`,
  `}`,
].join("\n") + "\n";

const write = (rel, c) => { fs.writeFileSync(path.join(ROOT, rel), c); console.log("wrote", rel); };
write("packages/core/src/icons.ts", ts);
console.log(`${entries.length} icons`);
