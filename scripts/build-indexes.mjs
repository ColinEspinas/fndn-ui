// Generates the index files from the specs and the files on disk, so adding a component never
// means hand-editing a shared file:
//   packages/core/css/index.css            tokens + Tailwind preset + base, layered
//   packages/react|vue|svelte/src/index.ts every adapter of that framework, with its exported types:
//                                          what the examples, the docs and the tests import as
//                                          @fndn/react, @fndn/vue and @fndn/svelte
import fs from "node:fs";
import path from "node:path";
import { ROOT, FRAMEWORKS, loadSpecs, exportLines, targetsOf } from "./lib.mjs";

const HEADER = "GENERATED by scripts/build-indexes.mjs — do not edit.";
const specs = loadSpecs().map((s) => s.spec);
const write = (rel, content) => {
  const p = path.join(ROOT, rel);
  if (fs.existsSync(p) && fs.readFileSync(p, "utf8") === content) return;
  fs.writeFileSync(p, content);
  console.log("wrote", rel);
};

write("packages/core/css/index.css", [
  `/* ${HEADER} */`,
  `/* fndn/ui — everything a Tailwind v4 stylesheet needs, after \`@import "tailwindcss"\`: the tokens, the`,
  ` * Tailwind preset (theme, token utilities, variants) and the hand-written CSS that remains (base`,
  ` * rules, motion, a few structural selectors). The hand-written CSS sits in the components layer,`,
  ` * so the utilities of a recipe and a user's className always win over it. Last, what the`,
  ` * project's fndn.json says about the look (config.css, which the tool writes in a project). */`,
  `@layer theme, base, components, utilities;`,
  `@import "./tokens.css";`,
  `@import "./tailwind.css";`,
  `@import "./base.css" layer(components);`,
  `@import "./config.css";`,
].join("\n") + "\n");

/* a framework the spec's `targets` does not list exports nothing for it */
for (const fw of FRAMEWORKS) {
  const lines = specs.filter((s) => targetsOf(s).includes(fw)).flatMap((s) => exportLines(s, fw, (f) => `../../../components/${s.name}/${f}`));
  write(`packages/${fw}/src/index.ts`, [`// ${HEADER}`, ...lines].join("\n") + "\n");
}
console.log(`indexes: ${specs.length} components`);
