/* The library as a project gets it from `npx fndn add`, per framework, built from the component
 * folders the way the tool's own data is (scripts/build-bundle.mjs): one folder per component in the
 * project's ui folder (`card/index.ts`, `card/Card.vue`, `card/card.recipe.ts`, its logic) and
 * `lib/` for what several components share, with the same relative imports. A component is its
 * index and everything that imports, followed to the end.
 *
 * Server only: read through lib/content.ts (recomputed in dev when one of the files changes). */
import { exportTable, indexLines, type ExportTable } from "../../../../packages/cli/src/imports.js";
import { derive, readText } from "./content";
import { targetsOf, type Framework } from "./types";

export type FileSpec = { name: string; files?: Record<string, string[]>; targets?: Framework[] };
/** A file as it lands in the ui folder: its content, the files it imports (paths in the ui folder)
 * and the npm packages it imports. */
export type LibFile = { content: string; imports: string[]; npm: string[] };
export type Library = {
  files: Record<string, LibFile>;
  /** a component's adapter files (paths in the ui folder) */
  components: Record<string, string[]>;
  /** every exported name and the component it belongs to (imports.js, exportTable) */
  exports: ExportTable;
};

const pascal = (k: string) => k.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());
const ADAPTER: Record<Framework, RegExp> = { react: /\.tsx$/, vue: /\.vue$/, svelte: /\.svelte$/ };
const RELATIVE = /(?:\bfrom\s+|\bimport\s+|\bimport\(\s*)["'](\.{1,2}\/[^"']+)["']/g;
const BARE = /(?:\bfrom\s+|\bimport\s+|\bimport\(\s*)["']([^"'./][^"']*)["']/g;
/* the framework itself is the project's; it is never something a component asks to install */
const RUNTIME = new Set(["react", "react-dom", "vue", "svelte"]);
const packageOf = (s: string) => (s.startsWith("@") ? s.split("/").slice(0, 2).join("/") : s.split("/")[0]!);

/** A file as the docs show it: without the "GENERATED by scripts/…" lines of the repository's build
 * (internal process, not something a reader acts on). */
export const stripGenerated = (code: string) => code.replace(/^(?:(?:\/\/|\/\*) GENERATED [^\n]*\n)+/, "");

/** The adapter file(s) of a component in a framework (names inside its folder). */
export function adapterFileNames(spec: FileSpec, fw: Framework): string[] {
  if (spec.files?.[fw]) return spec.files[fw]!;
  return fw === "react" ? [`${spec.name}.tsx`] : [`${pascal(spec.name)}.${fw}`];
}

/* posix path helpers for paths in the ui folder ("card/index.ts", "lib/tv.ts") */
function join(from: string, specifier: string): string {
  const out = from.split("/").slice(0, -1);
  for (const part of specifier.split("/")) {
    if (part === "..") out.pop();
    else if (part !== ".") out.push(part);
  }
  return out.join("/");
}

/** The library of one framework. `specs`: every component; `files`: the repository's files under
 * components/ (the caller's glob). */
function build(fw: Framework, specs: FileSpec[], files: string[]): Library {
  const sources: Record<string, string> = {};
  for (const f of files.filter((f) => f.startsWith("components/lib/") && f.endsWith(".ts") && !f.endsWith(".d.ts"))) sources[f.slice("components/".length)] = stripGenerated(readText(f));
  const components: Record<string, string[]> = {};
  const exportSources: Record<string, { file: string; source: string }[]> = {};
  for (const spec of specs.filter((s) => targetsOf(s).includes(fw))) {
    const dir = `components/${spec.name}/`;
    const mine = files.filter((f) => f.startsWith(dir) && !f.slice(dir.length).includes("/"));
    for (const f of mine) {
      const base = f.slice(dir.length);
      if ((base.endsWith(".ts") && !base.endsWith(".d.ts")) || ADAPTER[fw].test(base)) sources[`${spec.name}/${base}`] = readText(f);
    }
    const adapters = adapterFileNames(spec, fw).filter((f) => `${spec.name}/${f}` in sources);
    const withSource = adapters.map((file) => ({ file, source: sources[`${spec.name}/${file}`]! }));
    sources[`${spec.name}/index.ts`] = indexLines(fw, withSource, (f) => `./${f}`).join("\n") + "\n";
    components[spec.name] = adapters.map((f) => `${spec.name}/${f}`);
    exportSources[spec.name] = withSource;
  }
  const out: Record<string, LibFile> = {};
  for (const [name, content] of Object.entries(sources)) {
    const imports = new Set<string>();
    for (const m of content.matchAll(RELATIVE)) {
      const base = join(name, m[1]!);
      const hit = [base, `${base}.ts`, `${base}.tsx`].find((c) => c in sources);
      if (hit) imports.add(hit);
    }
    const npm = new Set([...content.matchAll(BARE)].map((m) => packageOf(m[1]!)).filter((p) => !RUNTIME.has(p)));
    out[name] = { content, imports: [...imports].sort(), npm: [...npm].sort() };
  }
  return { files: out, components, exports: exportTable(fw, exportSources) };
}

/** The library of a framework over the current files (recomputed in dev when one changes). */
export const libraryOf = (fw: Framework, specs: () => FileSpec[]): Library =>
  derive(`library:${fw}`, ["components/*/*.{json,ts,tsx,vue,svelte}"], (files) => build(fw, specs(), files));

export const indexOf = (name: string) => `${name}/index.ts`;
/** The component a file in the ui folder belongs to, or null for lib/ and the styles. */
export const ownerOf = (file: string) => { const d = file.split("/")[0]!; return d === "lib" || d === "styles" ? null : d; };

/** Every file the named components need, and the npm packages those files import (the tool's
 * `closure`, packages/cli/src/catalog.js). A component reached through one of its adapters comes
 * whole, with its index. */
export function closure(lib: Library, names: string[]): { files: string[]; npm: string[]; components: string[] } {
  const files = new Set<string>();
  const visit = (file: string) => {
    if (files.has(file) || !lib.files[file]) return;
    files.add(file);
    lib.files[file]!.imports.forEach(visit);
  };
  names.forEach((name) => visit(indexOf(name)));
  for (let grew = true; grew; ) {
    grew = false;
    for (const [name, adapters] of Object.entries(lib.components)) {
      if (!files.has(indexOf(name)) && adapters.some((f) => files.has(f))) { visit(indexOf(name)); grew = true; }
    }
  }
  const npm = new Set([...files].flatMap((f) => lib.files[f]!.npm));
  return { files: [...files].sort(), npm: [...npm].sort(), components: Object.keys(lib.components).filter((name) => files.has(indexOf(name))) };
}

/**
 * What a component page shows of one framework: the component's own folder (its index, adapters,
 * recipe, logic) and the lib/ files those import, followed to the end; and the components it is
 * built from (those are components of their own, with their own page, so the walk stops there).
 */
export function componentFiles(lib: Library, name: string): { files: string[]; builtFrom: string[] } {
  const files: string[] = [];
  const builtFrom = new Set<string>();
  const visit = (file: string) => {
    if (files.includes(file) || !lib.files[file]) return;
    const owner = ownerOf(file);
    if (owner && owner !== name) { builtFrom.add(owner); return; }
    files.push(file);
    lib.files[file]!.imports.forEach(visit);
  };
  visit(indexOf(name));
  /* the folder in its own order: index, adapters, recipe, the rest; then lib/ */
  const adapters = lib.components[name] ?? [];
  const rank = (f: string) => (f === indexOf(name) ? 0 : adapters.includes(f) ? 1 : f === `${name}/${name}.recipe.ts` ? 2 : ownerOf(f) ? 3 : 4);
  const order = (f: string) => (adapters.includes(f) ? adapters.indexOf(f) : 0);
  files.sort((a, b) => rank(a) - rank(b) || order(a) - order(b) || a.localeCompare(b));
  return { files, builtFrom: [...builtFrom].sort() };
}
